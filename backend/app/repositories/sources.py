from collections.abc import Iterable
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.domain.enums import Provenance, SourceKind
from app.models import Source, SourceSegment
from app.services.extraction.base import Segment


def create(
    db: Session,
    user_id: UUID,
    person_profile_id: UUID,
    *,
    id: UUID,  # noqa: A002 - pre-generated by the caller so the storage key can use it too
    kind: SourceKind,
    provenance: Provenance,
    filename: str | None,
    content_type: str | None,
    size_bytes: int,
    sha256: str,
    storage_key: str,
) -> Source:
    source = Source(
        id=id,
        user_id=user_id,
        person_profile_id=person_profile_id,
        kind=kind,
        provenance=provenance,
        filename=filename,
        content_type=content_type,
        size_bytes=size_bytes,
        sha256=sha256,
        storage_key=storage_key,
    )
    db.add(source)
    db.flush()
    return source


def get_owned(db: Session, user_id: UUID, source_id: UUID) -> Source | None:
    return db.scalar(select(Source).where(Source.id == source_id, Source.user_id == user_id))


def list_for_user(
    db: Session, user_id: UUID, *, person_profile_id: UUID | None = None, limit: int = 50
) -> list[Source]:
    stmt = select(Source).where(Source.user_id == user_id)
    if person_profile_id is not None:
        stmt = stmt.where(Source.person_profile_id == person_profile_id)
    return list(db.scalars(stmt.order_by(Source.created_at.desc()).limit(limit)))


def merge_metadata(db: Session, source: Source, extra: dict) -> Source:
    source.meta = {**source.meta, **extra}
    db.flush()
    return source


def replace_segments(
    db: Session, source: Source, segments: Iterable[Segment]
) -> list[SourceSegment]:
    """Idempotent: a job retry re-extracts and replaces rather than appending, so a flaky
    provider call after a successful extraction never leaves duplicate segments."""
    db.query(SourceSegment).filter(SourceSegment.source_id == source.id).delete()
    rows = [
        SourceSegment(
            user_id=source.user_id,
            person_profile_id=source.person_profile_id,
            source_id=source.id,
            ordinal=i,
            raw_text=seg.text,
            page=seg.page,
            char_start=seg.char_start,
            char_end=seg.char_end,
            t_start_ms=seg.t_start_ms,
            t_end_ms=seg.t_end_ms,
            speaker_label=seg.speaker_label,
            speaker_verified=seg.speaker_verified,
        )
        for i, seg in enumerate(segments)
    ]
    db.add_all(rows)
    db.flush()
    return rows


def segments_for(db: Session, source_id: UUID) -> list[SourceSegment]:
    stmt = select(SourceSegment).where(SourceSegment.source_id == source_id).order_by(
        SourceSegment.ordinal
    )
    return list(db.scalars(stmt))


def delete(db: Session, source: Source) -> None:
    db.delete(source)
    db.flush()
